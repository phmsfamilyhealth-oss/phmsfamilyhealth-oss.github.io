import test from 'node:test';
import assert from 'node:assert/strict';
import {validateAppointmentDraft as validate} from '../contracts/scenario-validator.mjs';
const org={id:'h1'}, unit={id:'u1',organization_id:'h1'},doc={id:'d1',organization_id:'h1',service_unit_id:'u1'};
const base={scenario:'booked',date:'2026-11-03',time_known:true,time:'09:30',organization:org,service_unit:unit,clinician:doc};
const check=(name,change,expected)=>test(name,()=>{const r=validate({...base,...change});assert.equal(r.ok,expected,JSON.stringify(r))});
check('confirmed booking valid',{},true);
check('walkin no time valid',{scenario:'walk_in',time_known:false,time:null,status:'planned'},true);
check('historical dated visit valid in draft only',{scenario:'historical',time_known:false,time:null,status:'completed'},true);
check('booked without time rejected',{time_known:false,time:null},false);
check('unknown-time with time entered rejected',{scenario:'walk_in',time_known:false,time:'09:00'},false);
check('invalid date rejected',{date:'2026-02-30'},false);
check('invalid time rejected',{time:'25:30'},false);
check('doctor wrong hospital rejected',{clinician:{...doc,organization_id:'h2'}},false);
check('unit wrong hospital rejected',{service_unit:{...unit,organization_id:'h2'}},false);
check('doctor wrong clinic rejected',{clinician:{...doc,service_unit_id:'u2'}},false);
check('deactivated doctor rejected',{clinician:{...doc,deleted_at:'2026-10-27'}},false);
check('historical without completed rejected',{scenario:'historical'},false);
check('walk-in status completed rejected',{scenario:'walk_in',status:'completed'},false);
test('non-object rejected',()=>assert.equal(validate(null).ok,false));
